export function setLang(value) {
  dict = value === "en" ? en : ja;
  document.documentElement.lang = value === "en" ? "en" : "ja";
}

export function t(key, ...args) {
  const v = dict[key] ?? ja[key] ?? key;
  return typeof v === "function" ? v(...args) : v;
}
